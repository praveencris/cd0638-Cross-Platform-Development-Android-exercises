package com.recall.app.data.local.dao

import androidx.room.Dao
import androidx.room.Insert
import androidx.room.OnConflictStrategy
import androidx.room.Query
import androidx.room.Transaction
import com.recall.app.data.local.entity.CardEntity
import com.recall.app.data.local.entity.DeckEntity
import com.recall.app.data.local.entity.DeckWithCards
import kotlinx.coroutines.flow.Flow

@Dao
interface RecallDao {
    @Query("SELECT * FROM DeckEntity")
    fun getDecks(): Flow<List<DeckEntity>>

    /**
     * Efficient query that fetches decks with their cards in a single database operation
     *
     * Performance optimization:
     * - @Transaction ensures consistent read across multiple tables
     * - @Relation annotation triggers SQL LEFT JOIN automatically
     * - Replaces N+1 query pattern (1 deck query + N card queries per deck)
     * - Result: 1 query instead of 1+N queries
     *
     * SQL generated by Room (approximate):
     * SELECT DeckEntity.*, CardEntity.*
     * FROM DeckEntity
     * LEFT JOIN CardEntity ON DeckEntity.id = CardEntity.deckId
     *
     * @return Flow that emits list of decks with their cards whenever database changes
     */
    @Transaction
    @Query("SELECT * FROM DeckEntity")
    fun getDecksWithCards(): Flow<List<DeckWithCards>>

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertDeck(deck: DeckEntity)

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertCards(cards: List<CardEntity>)

    @Query("SELECT * FROM CardEntity WHERE deckId = :deckId")
    suspend fun getCardsForDeck(deckId: String): List<CardEntity>

    @Query("UPDATE DeckEntity SET currentCardIndex = :cardIndex WHERE id = :deckId")
    suspend fun updateDeckProgress(deckId: String, cardIndex: Int)
}
